// ++a mean pre-increment. Which tells us to increment the value of a by 1 before using it in the expression.
// a++ mean post-increment. Which tells us to use the current value of a in the expression and then increment it by 1 after the expression is evaluated.

let a = 5;
let b = ++a; // pre-increment
console.log(b); // Output: 6 (a is incremented before assignment to b)