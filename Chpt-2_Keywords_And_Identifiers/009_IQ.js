// Every variable name is an identifier, but not every identifier is a variable.

// 1. Camel case: (Follow this convention for variable names)
let myName = "Rahul";

// 2. Pascal case: (Follow this convention for class and constructor names)
let MyName = "Rahul";

// 3. Snake case: (_ separate words with underscore)
let my_name = "Rahul";

// 4. Screaming snake case: (All letters are capitalized and words are separated by underscores)
let MY_NAME = "Rahul";

// 5. Hungarian notation: (Prefix the variable name with a lowercase letter that indicates its type)
let strMyName = "Rahul";